const { GoogleGenAI } = require("@google/genai");
const puppeteer = require("puppeteer");
const ai = new GoogleGenAI({
    apiKey: process.env.GOOGLE_GENAI_API_KEY,
});

const questionSchema = {
    type: "object",
    properties: {
        question: { type: "string" },
        intention: { type: "string" },
        answer: { type: "string" },
    },
    required: ["question", "intention", "answer"],
    additionalProperties: false,
};

const interviewReportSchema = {
    type: "object",
    properties: {
        title: { type: "string" },
        matchScore: { type: "number", minimum: 0, maximum: 100 },
        technicalQuestions: {
            type: "array",
            items: questionSchema,
        },
        behavioralQuestions: {
            type: "array",
            items: questionSchema,
        },
        skillGaps: {
            type: "array",
            items: {
                type: "object",
                properties: {
                    skill: { type: "string" },
                    severity: { type: "string", enum: ["low", "medium", "high"] },
                },
                required: ["skill", "severity"],
                additionalProperties: false,
            },
        },
        preparationPlan: {
            type: "array",
            items: {
                type: "object",
                properties: {
                    day: { type: "number" },
                    focus: { type: "string" },
                    tasks: {
                        type: "array",
                        items: { type: "string" },
                    },
                },
                required: ["day", "focus", "tasks"],
                additionalProperties: false,
            },
        },
    },
    required: [
        "title",
        "matchScore",
        "technicalQuestions",
        "behavioralQuestions",
        "skillGaps",
        "preparationPlan",
    ],
    additionalProperties: false,
    title: "Interview Report Schema",
};

async function generateInterviewReport({ resume, selfDescription, jobDescription }) {
    const prompt = `Generate an interview report for a candidate based on the following information.
                    Return only JSON matching the provided schema. Include every required field,
                    including a concise title for the interview plan,
                    including preparationPlan. Each question must contain question, intention, and answer.
                    Resume: ${resume}
                    Self Description: ${selfDescription}
                    Job Description: ${jobDescription}`;

    const response = await ai.models.generateContent({
        model: "gemini-3.5-flash-lite",
        contents: prompt,
        config: {
            responseMimeType: "application/json",
            responseJsonSchema: interviewReportSchema,
        }
    });

    return JSON.parse(response.text);
}

